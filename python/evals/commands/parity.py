"""Export a fixture that lets Dart tests reproduce the lab's retrieval score.

The app is a second implementation of a pipeline that was measured in Python:
same chunks, same vectors, same fusion weights, different language. Nothing
guarantees the two agree, and every way they can disagree is silent -- a
tokenizer that splits differently, a prefix that is not applied, an RRF weight
that was retyped as 1.0, a transliterated query that reaches the dense leg
anyway. None of those throw. They just make retrieval worse on the device than
in the report, which is the one failure an eval by construction cannot see.

This writes the query vectors and the expected ranking for the whole retrieval
golden set, so a `flutter test` can drive the real Dart retriever and assert it
returns the same passages in the same order.

Two rankings are exported, because only one of them can be asserted exactly.

The dense leg is fully determined: the same vectors, the same cosine. Dart must
reproduce the *scores*, which is the check that the shipped artifacts and the
fusion inputs are right. Not the ranks -- cosines over one corpus cluster
tightly enough that a 1e-7 difference between numpy's float64 dot product and
Dart's accumulation reorders near-ties, so an ordering assertion would fail on
arithmetic that is entirely correct.

The fused ranking cannot match exactly and never could. The lexical legs are
Okapi BM25 here and SQLite FTS5's ``bm25()`` on the device -- the same family,
different stemmers, different stopword lists, different tie-breaking. Demanding
equality there would only teach us to delete the test. What is asserted instead
is agreement: enough overlap to catch a missing task prefix, a retyped RRF
weight, or a transliterated query reaching the dense leg, none of which throw.

Neither covers the ONNX forward pass itself, which needs a device -- and whose
Python equivalent is already checked against PyTorch.
"""

from __future__ import annotations

import argparse
import json
import struct
from pathlib import Path

from survive_rag.config import RECOMMENDED
from survive_rag.corpus.loader import load_corpus
from survive_rag.retrieval.embedder import load_embedder
from survive_rag.retrieval.pipeline import Retriever

from ..harness.goldset import load_goldset
from ..harness.lab import goldset_path

TOP_K = 5
# More than TOP_K: the boundary of the top 5 is where near-ties swap, so the
# fixture carries a few beyond it to make that visible rather than surprising.
DENSE_K = 8


def cmd_parity(args: argparse.Namespace) -> int:
    """Write query vectors and expected rankings for the Dart parity test."""
    config = RECOMMENDED.with_(
        use_dense_leg=True,
        embed_model=args.embed_model,
        embed_backend=args.embed_backend,
    )
    corpus = load_corpus(cfg=config.chunking, passages=config.passages)
    retriever = Retriever(corpus=corpus, config=config)
    goldset = load_goldset(goldset_path("retrieval")).cases

    embedder = load_embedder(config.embed_model, backend=config.embed_backend)
    queries = [case.query for case in goldset]
    vectors = embedder.encode(queries, is_query=True)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    with (out / "query_vectors.f32").open("wb") as handle:
        for row in vectors:
            handle.write(struct.pack(f"<{len(row)}f", *row.tolist()))

    cases = []
    for case in goldset:
        hits = retriever.retrieve(case.query, top_k=TOP_K)
        dense = retriever.dense_scores(case.query, limit=DENSE_K)
        cases.append(
            {
                "id": case.case_id,
                "query": case.query,
                "expected": [hit.unit.chunk_id for hit in hits],
                "dense_scores": [[unit, round(score, 6)] for unit, score in dense],
                "slices": sorted(case.slices),
            }
        )

    (out / "retrieval_parity.json").write_text(
        json.dumps(
            {
                "note": "generated by `python -m evals parity`; do not edit by hand",
                "model": config.embed_model,
                "backend": config.embed_backend,
                "dim": int(vectors.shape[1]),
                "top_k": TOP_K,
                "cases": cases,
            },
            ensure_ascii=False,
            indent=1,
        ),
        encoding="utf-8",
    )
    print(f"{len(cases)} cases -> {out}")
    return 0


def add_parser(sub: argparse._SubParsersAction) -> None:
    """Register the ``parity`` command."""
    parser = sub.add_parser(
        "parity", help="export the Dart retrieval parity fixture"
    )
    parser.add_argument("--out", default="../test/fixtures", help="fixture directory")
    parser.add_argument("--embed-model", default=RECOMMENDED.embed_model)
    parser.add_argument("--embed-backend", default="onnx", choices=("torch", "onnx"))
    parser.set_defaults(func=cmd_parity)
